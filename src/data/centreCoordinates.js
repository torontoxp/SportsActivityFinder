export function getDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) * Math.cos(lat2 * (Math.PI / 180)) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

export function getScheduleDistance(scheduleRow, userLocation) {
  if (!userLocation || userLocation.lat == null || userLocation.lng == null) return null;
  
  // 1. Prefer dynamic API coordinates returned from Lambda backend
  // 2. Fall back to local coordinate mapping
  const lat = scheduleRow.lat ?? scheduleRow.latitude ?? CENTRE_COORDINATES[scheduleRow.community_center_id]?.lat;
  const lng = scheduleRow.lng ?? scheduleRow.longitude ?? CENTRE_COORDINATES[scheduleRow.community_center_id]?.lng;
  
  if (lat == null || lng == null) return null;
  return getDistanceKm(userLocation.lat, userLocation.lng, lat, lng);
}
